import { build } from 'esbuild';
import { mkdir, copyFile } from 'node:fs/promises';
import { browserBuildOptions } from './browser-build.mjs';
await mkdir('.writer-build/assets', { recursive: true });
await build({ ...browserBuildOptions, entryPoints: ['writer/ui/app.mjs'], outfile: '.writer-build/assets/app.js', minify: true });
await build({ ...browserBuildOptions, entryPoints: ['writer/ui/stats.mjs'], outfile: '.writer-build/assets/stats.js', minify: true });
await build({ entryPoints: ['writer/worker.mjs'], bundle: true, format: 'esm', platform: 'browser', target: 'es2022', outfile: '.writer-build/worker.mjs', minify: true });
await copyFile('writer/ui/index.html', '.writer-build/assets/index.html');
await copyFile('writer/ui/app.css', '.writer-build/assets/app.css');
await copyFile('writer/ui/stats.html', '.writer-build/assets/stats.html');
await copyFile('writer/ui/stats.css', '.writer-build/assets/stats.css');
console.log('Built writer UI and Worker.');
